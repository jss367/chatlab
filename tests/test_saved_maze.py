"""Maze runs saved by earlier ChatLab versions keep loading, and keep reading the same way.

Every file under fixtures/saved/maze was written by the ChatLab of its era,
from a worktree of the commit its README row names, by that commit's own
writer, and committed as it came out. Nothing here builds an old file from
current code, so a change to how a saved run is read, rather than to how a
new one is written, has frozen bytes to fail against.

Each run is loaded the way Load a saved run loads it, read_run_file and
from_payload with the page's prompt reader over the test model, and the
facts a reader of the results depends on are asserted: where each agent
ended up and how, the exits, the mail, the counts, and what a field the
file predates is read as. The same facts are asserted again after the run is
saved by today's writer and read back. A snapshot of the whole re-export
would churn with every new optional field, so the facts are named instead.
"""
