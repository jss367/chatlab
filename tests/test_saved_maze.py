    def test_the_first_runs_read_with_the_goal_prompts_and_window_they_were_scored_under(self):
        # b206b5e: before goal_mode, goal_hint, the editable prompts, the recovery window and the history field.
        data = read_run_file(FIXTURES / "run-1-before-goal-mode.json")
        self.assertFalse({"goal_mode", "goal_hint", "system_prompt", "instruction", "recovery_tokens",
                          "recovery_attempts", "reasoning_history"} & set(data["config"]))
        def check(ep):
            self.assertEqual({k: ep.config[k] for k in ("goal_mode", "goal_hint", "recovery_tokens", "recovery_attempts")},
                             dict(goal_mode="coordinates", goal_hint="", recovery_tokens=1024, recovery_attempts=4))
            self.assertEqual(ep.config["system_prompt"], SYSTEM)
            self.assertEqual(ep.config["instruction"], default_instruction("coordinates"))
            self.assertEqual(ep.messages[0], {"role": "system", "content": SYSTEM})
            self.assertTrue(ep.messages[1]["content"].startswith(ep.config["instruction"] + "\n"))
            self.assertEqual((ep.phase, ep.position, tuple(ep.maze.goal)), ("arrived", (3, 4), (3, 4)))
            self.assertEqual((ep.supplied_moves, ep.moves, ep.tool_attempts, len(ep.turns), ep.rounds), (2, 10, 11, 11, 11))
            self.assertEqual(errors(ep), [None, "blocked_move", None, "wrong_maze", "invalid_arguments"] + [None] * 6)
            self.assertEqual(path_of(ep), [(3, 1), (3, 0), (2, 0), (1, 0), (1, 1), (1, 2), (1, 3), (2, 3), (3, 3), (3, 4)])
            self.assertEqual((ep.interrupted, ep.intervention_turn, ep.resumed, ep.first_move_progress, ep.latency),
                             (True, 1, True, True, 348))
            self.assertEqual(ep.turns[1]["prefix_text"], "Distracted by a noise. ")
            self.assertFalse(ep.manual_intervention)
            self.assertEqual(ep.sampled_tokens, 1609)
            # A call written inside reasoning was never one: one attempt a response.
            self.assertIn("<tool_call>", ep.turns[2]["text"].split("</think>")[0])
            # Its maze was drawn before runs recorded the probability, which is searched for.
            self.assertEqual(openness_of(ep), .7)
        self.both("run-1-before-goal-mode.json", check)
        # The interrupted response and the one with an unreadable call are not scored.
        rows = read_responses(load_run(data))
        self.assertEqual([row.index for row in rows], [1, 3, 4, 6, 7, 8, 9, 10, 11])
        self.assertEqual([(row.stated, row.taken) for row in rows][3:], [("east", "east")] * 3
                         + [("south", "south")] * 2 + [("east", "east")])

