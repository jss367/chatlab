def reader(run, turn, context):
    return prompt_reading(run, turn, context, MODEL)


def load(path):
    return from_payload(read_run_file(path), read_prompt=reader)


def errors(ep):
    return [event["error"] for event in ep.events if event["source"] == "model"]


def path_of(ep, agent=0):
    """Every cell an agent's accepted moves took it to, supplied moves included."""
    return [tuple(e["after"]) for e in ep.events if e["accepted"] and e.get("agent", 0) == agent]


def steered(ep):
    """The steered responses, as (round, agent) on a team and as indices on a run of one agent."""
    if ep.team:
        return [(t["round"], t["agent"]) for t in ep.turns if t.get("steered")]
    return [i for i, t in enumerate(ep.turns) if t.get("steered")]


def statuses(ep):
    return [(a["position"], a["status"], a.get("exit")) for a in ep.agents]


def assistant_messages(ep, agent=0):
    return [m for m in ep.agents[agent]["messages"] if m["role"] == "assistant"]


class SavedMazeRunTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)

    def readings(self, name):
        """The run as loaded from its fixture, then saved by today's writer and loaded again."""
        first = load(FIXTURES / name)
        again = load(first.save(Path(self.directory.name) / name.removesuffix(".json")))
        return (("as saved", first), ("saved again", again))

    def both(self, name, check):
        """Assert ``check`` of the run as saved and of the run saved again."""
        for label, ep in self.readings(name):
            with self.subTest(name, reading=label):
                check(ep)

    # Every fixture.

    def test_every_fixture_is_listed_and_loads_as_its_format(self):
        on_disk = {path.name for path in FIXTURES.glob("*.json") if not path.name.startswith("trials-")}
        self.assertEqual(on_disk, set(FORMATS))
        for name, marker in FORMATS.items():
            with self.subTest(name):
                data = read_run_file(FIXTURES / name)
                self.assertEqual(data["format"], marker)
                ep = from_payload(data, read_prompt=reader)
                self.assertTrue(ep.replay_only)
                self.assertEqual(ep.run_id, data["run_id"])
                self.assertEqual(ep.phase, data["phase"])
                # Loaded beside a model that did not record it, as most uploads are, no prompt is read
                # and the run reads the same.
                beside = from_payload(read_run_file(FIXTURES / name),
                                      read_prompt=lambda run, turn, context: prompt_reading(run, turn, context, OTHER))
                self.assertEqual((beside.phase, beside.moves, beside.sampled_tokens), (ep.phase, ep.moves, ep.sampled_tokens))
                # The Reasoning check reads the same run the same way.
                checked = load_run(read_run_file(FIXTURES / name))
                self.assertEqual((checked.phase, len(checked.turns), checked.moves), (ep.phase, len(ep.turns), ep.moves))

    def test_every_recorded_prompt_is_the_history_the_run_records_for_it(self):
        for name in sorted(set(FORMATS) - PLACEHOLDER_PROMPTS):
            def check(ep):
                read = 0
                for index, turn in enumerate(ep.turns):
                    if not turn.get("prompt_ids"):
                        continue
                    recorded, templated = reader(ep, turn, context_messages(ep, index))
                    self.assertEqual(recorded, templated, f"response {index + 1}")
                    read += 1
                self.assertEqual(read, sum(bool(t["metrics"]) for t in ep.turns))
            self.both(name, check)

    def test_a_template_that_cannot_render_the_history_still_finds_it_in_every_recorded_prompt(self):
        # The page falls back to finding each message in the decoded prompt when the
        # loaded template refuses the messages. Every run whose prompts are read loads under it.
        def decoded_only(run, turn, context):
            reading = reader(run, turn, context)
            return None if reading is None else (reading[0], None)
        for name in ("run-3-inserts.json", "run-3-stopped.json", "run-3-current-changing-map.json",
                     "team-2-map-change-messages.json", "team-3-rule-1.json", "team-3-current.json"):
            with self.subTest(name):
                ep = from_payload(read_run_file(FIXTURES / name), read_prompt=decoded_only)
                self.assertEqual(ep.phase, read_run_file(FIXTURES / name)["phase"])

    def test_a_run_written_before_the_history_field_keeps_reasoning_in_its_content(self):
        for name in FORMATS:
            data = read_run_file(FIXTURES / name)
            def check(ep):
                assistants = [m for a in range(len(ep.agents)) for m in assistant_messages(ep, a)]
                if "reasoning_history" in data["config"]:
                    self.assertEqual(ep.config["reasoning_history"], "reasoning_content")
                    # A response that opened with its reasoning keeps it in its own field. One an
                    # interruption opened has text before the block, and keeps it in its content.
                    self.assertFalse(any(m["content"].startswith("<think>") for m in assistants))
                    self.assertTrue(any("reasoning_content" in m for m in assistants))
                else:
                    self.assertEqual(ep.config["reasoning_history"], "content")
                    self.assertFalse(any("reasoning_content" in m for m in assistants))
                    # Each response that reasoned keeps the whole block in its content.
                    thought = [m for m in assistants if "</think>" in m["content"]]
                    self.assertEqual(bool(thought), name not in WITHOUT_REASONING)
                    self.assertTrue(all("<think>" in m["content"] for m in thought))
            self.both(name, check)

